(() => {
  "use strict";
  const { safeFileName, countWords, buildHtmlDocument } = TextEditorUtils;
  const editor = document.querySelector("#editor");
  const title = document.querySelector("#document-title");
  const status = document.querySelector("#status");
  const count = document.querySelector("#document-count");
  const fileInput = document.querySelector("#file-input");
  const storageKey = "text-editor-draft-v2";
  let saveTimer = null;

  function updateCount() {
    const content = editor.innerText || "";
    count.textContent = countWords(content) + " words · " + content.length + " characters";
  }
  function setStatus(message) { status.textContent = message; }
  function saveDraft() {
    try {
      localStorage.setItem(storageKey, JSON.stringify({ title: title.value, html: editor.innerHTML }));
      setStatus("Saved in this browser");
    } catch {
      setStatus("Browser storage unavailable. Download a copy.");
    }
  }
  function scheduleSave() {
    updateCount();
    setStatus("Editing…");
    clearTimeout(saveTimer);
    saveTimer = setTimeout(saveDraft, 450);
  }
  function clearPendingSave() { clearTimeout(saveTimer); saveTimer = null; }
  function restoreDraft() {
    try {
      const saved = JSON.parse(localStorage.getItem(storageKey) || "null");
      if (saved && typeof saved.title === "string" && typeof saved.html === "string") {
        title.value = saved.title;
        // Only retain markup generated by this editor; strip external elements and attributes.
        const temp = document.createElement("div");
        temp.innerHTML = saved.html;
        sanitizeMarkup(temp);
        editor.innerHTML = temp.innerHTML;
        setStatus("Restored from this browser");
      }
    } catch { setStatus("Ready to write"); }
    updateCount();
  }
  function sanitizeMarkup(root) {
    const allowed = new Set(["B","STRONG","I","EM","DIV","P","BR","SPAN"]);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT);
    const elements = [];
    while (walker.nextNode()) elements.push(walker.currentNode);
    for (const el of elements.reverse()) {
      if (!allowed.has(el.tagName)) {
        el.replaceWith(document.createTextNode(el.textContent || ""));
      } else {
        const align = el.style.textAlign;
        for (const attr of [...el.attributes]) el.removeAttribute(attr.name);
        if (["left", "right", "center"].includes(align) && ["DIV","P"].includes(el.tagName))
          el.style.textAlign = align;
      }
    }
  }
  function download(filename, contents, type) {
    const blob = new Blob([contents], { type });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    setStatus("Downloaded " + filename);
  }
  function applyCommand(command) {
    editor.focus();
    document.execCommand(command, false, null);
    scheduleSave();
  }
  function transformSelection(mode) {
    const selection = window.getSelection();
    if (!selection || selection.isCollapsed || !selection.rangeCount) {
      setStatus("Select text to change its case.");
      return;
    }
    const range = selection.getRangeAt(0);
    if (!editor.contains(range.commonAncestorContainer)) {
      setStatus("Select text in the document.");
      return;
    }
    const selectedText = selection.toString();
    if (!selectedText) return;
    const replacement = mode === "upper" ? selectedText.toLocaleUpperCase() : selectedText.toLocaleLowerCase();
    range.deleteContents();
    const textNode = document.createTextNode(replacement);
    range.insertNode(textNode);
    selection.removeAllRanges();
    const after = document.createRange();
    after.setStartAfter(textNode);
    after.collapse(true);
    selection.addRange(after);
    scheduleSave();
  }
  // Prevent formatting button clicks from clearing the current text selection.
  document.querySelectorAll("[data-command],[data-transform]").forEach(button => {
    button.addEventListener("mousedown", event => event.preventDefault());
    button.addEventListener("click", () => {
      if (button.dataset.command) applyCommand(button.dataset.command);
      else transformSelection(button.dataset.transform);
    });
  });
  document.querySelector("#open-file").addEventListener("click", () => fileInput.click());
  fileInput.addEventListener("change", async () => {
    const file = fileInput.files && fileInput.files[0];
    if (!file) return;
    if (!/\.txt$/i.test(file.name) || file.size > 2 * 1024 * 1024) {
      setStatus("Please choose a .txt file smaller than 2 MB.");
      fileInput.value = "";
      return;
    }
    try {
      const contents = await file.text();
      editor.textContent = contents; // Imported files are always treated as plain text.
      title.value = file.name.replace(/\.txt$/i, "") || "Untitled document";
      clearPendingSave();
      updateCount();
      saveDraft();
      setStatus("Opened " + file.name);
    } catch { setStatus("Could not open that file."); }
    fileInput.value = "";
  });
  document.querySelector("#download-txt").addEventListener("click", () => {
    download(safeFileName(title.value) + ".txt", editor.innerText || "", "text/plain;charset=utf-8");
  });
  document.querySelector("#download-html").addEventListener("click", () => {
    const cloned = editor.cloneNode(true);
    sanitizeMarkup(cloned);
    const content = buildHtmlDocument(title.value || "Untitled document", cloned.innerHTML);
    download(safeFileName(title.value) + ".html", content, "text/html;charset=utf-8");
  });
  document.querySelector("#clear-editor").addEventListener("click", () => {
    if (!(editor.innerText || "").trim()) { setStatus("The page is already empty."); return; }
    if (!window.confirm("Clear this document? Download a copy first if you want to keep it.")) return;
    editor.replaceChildren();
    scheduleSave();
    editor.focus();
  });
  editor.addEventListener("input", scheduleSave);
  title.addEventListener("input", scheduleSave);
  editor.addEventListener("paste", event => {
    const text = event.clipboardData && event.clipboardData.getData("text/plain");
    if (text === undefined || text === null) return;
    event.preventDefault();
    document.execCommand("insertText", false, text);
  });
  window.addEventListener("beforeunload", () => { if (saveTimer) saveDraft(); });
  restoreDraft();
})();
